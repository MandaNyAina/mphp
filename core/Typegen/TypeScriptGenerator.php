<?php

declare(strict_types=1);

namespace Mphp\Typegen;

use BackedEnum;
use DateTimeInterface;
use Mphp\Http\FormRequest;
use Mphp\Http\Response;
use Mphp\Routing\RouteDefinition;
use Mphp\Routing\Router;
use ReflectionClass;
use ReflectionEnum;
use ReflectionMethod;
use ReflectionNamedType;
use ReflectionProperty;
use ReflectionType;
use ReflectionUnionType;

/**
 * PHP is the source of truth: public properties of the classes in app/Data become TypeScript
 * interfaces, and named routes become a typed route() helper. No Node server, no OpenAPI file.
 */
final class TypeScriptGenerator
{
    private const BANNER = "// AUTO-GENERATED by `php bin/mphp types:generate`. Do not edit by hand.\n";

    public function __construct(private readonly string $dataDirectory, private readonly string $dataNamespace) {}

    public function types(): string
    {
        $blocks = [];

        foreach ($this->classes() as $class) {
            $blocks[] = $class->isEnum() ? $this->enumType(new ReflectionEnum($class->getName())) : $this->interfaceType($class);
        }

        return self::BANNER . "\n" . implode("\n", $blocks);
    }

    public function routes(Router $router): string
    {
        $entries = [];
        $params = [];
        $responses = [];
        $bodies = [];

        foreach ($router->routes() as $route) {
            if ($route->name === null) {
                continue;
            }
            $name = $this->quote($route->name);
            $path = (string) preg_replace('/\{(\w+):[^}]+\}/', '{$1}', $route->path);
            $entries[] = sprintf("  '%s': { method: '%s', path: '%s' },", $name, $route->method, $this->quote($path));
            $responses[] = sprintf("  '%s': %s;", $name, $this->responseType($route));
            if (($body = $this->bodyType($route)) !== null) {
                $bodies[] = sprintf("  '%s': %s;", $name, $body);
            }

            if ($route->paramNames !== []) {
                $fields = implode('; ', array_map(static fn(string $p): string => "$p: string | number", $route->paramNames));
                $params[] = sprintf("  '%s': { %s };", $name, $fields);
            }
        }

        $names = array_map(static fn(ReflectionClass $c): string => $c->getShortName(), $this->classes());
        $import = $names === [] ? '' : 'import type { ' . implode(', ', $names) . " } from './types';\n\n";
        $paramBlock = $params === [] ? "export interface RouteParams {}\n" : "export interface RouteParams {\n" . implode("\n", $params) . "\n}\n";
        $responseBlock = $responses === [] ? "export interface RouteResponses {}\n" : "/** What each route answers with (from the PHP return type or #[Ts]). */\nexport interface RouteResponses {\n" . implode("\n", $responses) . "\n}\n";

        $bodyBlock = $bodies === [] ? "export interface RouteBodies {}\n" : "/** JSON body each route expects (from the FormRequest rules). */\nexport interface RouteBodies {\n" . implode("\n", $bodies) . "\n}\n";

        return self::BANNER . "\n" . $import . "export const routes = {\n" . implode("\n", $entries) . "\n} as const;\n\n"
            . "export type Routes = typeof routes;\nexport type RouteName = keyof Routes;\n\n"
            . $paramBlock . "\n" . $responseBlock . "\n" . $bodyBlock . "\n"
            . "export type ParamsOf<N extends RouteName> = N extends keyof RouteParams ? RouteParams[N] : undefined;\n\n"
            . "/** route('names.update', { id: 3 }) => '/api/names/3' */\n"
            . "export function route<N extends RouteName>(name: N, ...args: ParamsOf<N> extends undefined ? [] : [params: ParamsOf<N>]): string {\n"
            . "  const params = (args[0] ?? {}) as Record<string, string | number>;\n"
            . "  return routes[name].path.replace(/\\{(\\w+)\\}/g, (_, key: string) => encodeURIComponent(String(params[key])));\n"
            . "}\n";
    }

    /** `{ firstname: string; bio?: string | null }` for actions that type-hint a FormRequest, else null. */
    private function bodyType(RouteDefinition $route): ?string
    {
        if (!is_array($route->handler)) {
            return null;
        }

        foreach ((new ReflectionMethod($route->handler[0], $route->handler[1]))->getParameters() as $parameter) {
            $type = $parameter->getType();
            if (!$type instanceof ReflectionNamedType || !is_subclass_of($type->getName(), FormRequest::class)) {
                continue;
            }

            $constructor = (new ReflectionClass($type->getName()))->getConstructor();
            $rules = $type->getName()::fields();
            $fields = [];
            foreach ($constructor?->getParameters() ?? [] as $field) {
                $optional = !in_array('required', $rules[$field->getName()] ?? [], true);
                $override = $field->getAttributes(Ts::class)[0] ?? null;
                $fields[] = sprintf('%s%s: %s', $field->getName(), $optional ? '?' : '', $override?->newInstance()->type ?? $this->tsType($field->getType()));
            }

            return '{ ' . implode('; ', $fields) . ' }';
        }

        return null;
    }

    private function responseType(RouteDefinition $route): string
    {
        if (!is_array($route->handler)) {
            return 'unknown';
        }

        $method = new ReflectionMethod($route->handler[0], $route->handler[1]);
        $override = $method->getAttributes(Ts::class)[0] ?? null;
        if ($override !== null) {
            return $override->newInstance()->type;
        }

        $type = $method->getReturnType();

        return ($type instanceof ReflectionNamedType && $type->getName() === Response::class) ? 'unknown' : $this->tsType($type);
    }

    /** @return list<ReflectionClass<object>> */
    private function classes(): array
    {
        if (!is_dir($this->dataDirectory)) {
            return [];
        }

        $paths = [];
        foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($this->dataDirectory, \FilesystemIterator::SKIP_DOTS)) as $file) {
            if ($file->getExtension() === 'php') {
                $paths[] = $file->getPathname();
            }
        }
        sort($paths);

        $classes = [];
        foreach ($paths as $path) {
            $relative = substr($path, strlen(rtrim($this->dataDirectory, '/')) + 1, -4);
            $name = $this->dataNamespace . '\\' . str_replace('/', '\\', $relative);

            if (class_exists($name) || enum_exists($name)) {
                $classes[] = new ReflectionClass($name);
            }
        }

        return $classes;
    }

    /** @param ReflectionClass<object> $class */
    private function interfaceType(ReflectionClass $class): string
    {
        $lines = [];
        foreach ($class->getProperties(ReflectionProperty::IS_PUBLIC) as $property) {
            $override = $property->getAttributes(Ts::class)[0] ?? null;
            $type = $override !== null ? $override->newInstance()->type : $this->tsType($property->getType());
            $lines[] = sprintf('  %s: %s;', $property->getName(), $type);
        }

        return sprintf("export interface %s {\n%s\n}\n", $class->getShortName(), implode("\n", $lines));
    }

    /** @param ReflectionEnum<BackedEnum> $enum */
    private function enumType(ReflectionEnum $enum): string
    {
        $values = array_map(
            static fn(\ReflectionEnumBackedCase $case): string => is_int($case->getBackingValue()) ? (string) $case->getBackingValue() : "'" . addslashes((string) $case->getBackingValue()) . "'",
            array_filter($enum->getCases(), static fn($case): bool => $case instanceof \ReflectionEnumBackedCase),
        );

        return sprintf("export type %s = %s;\n", $enum->getShortName(), $values === [] ? 'never' : implode(' | ', $values));
    }

    private function tsType(?ReflectionType $type): string
    {
        if ($type === null) {
            return 'unknown';
        }

        if ($type instanceof ReflectionUnionType) {
            return implode(' | ', array_unique(array_map($this->tsType(...), $type->getTypes())));
        }

        if (!$type instanceof ReflectionNamedType) {
            return 'unknown';
        }

        $name = $type->getName();
        $mapped = match ($name) {
            'int', 'float' => 'number',
            'string' => 'string',
            'bool', 'true', 'false' => 'boolean',
            'array', 'iterable' => 'unknown[]',
            'object' => 'Record<string, unknown>',
            'null' => 'null',
            'void' => 'void',
            'mixed' => 'unknown',
            default => $this->classType($name),
        };

        return $type->allowsNull() && $name !== 'mixed' && $name !== 'null' ? "$mapped | null" : $mapped;
    }

    private function classType(string $name): string
    {
        if (is_a($name, DateTimeInterface::class, true)) {
            return 'string';
        }

        return str_starts_with($name, $this->dataNamespace . '\\') ? (new ReflectionClass($name))->getShortName() : 'unknown';
    }

    private function quote(string $value): string
    {
        return addcslashes($value, "'\\");
    }
}
